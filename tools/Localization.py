"""Export first-batch RimWorld Keyed strings and inventory remaining C# literals."""
import argparse
import csv
import json
import re
import string
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKEN = re.compile(r'@"(?:[^"]|"")*"|"(?:\\.|[^"\\])*"')
CJK = re.compile(r'[\u4e00-\u9fff]')


def entries():
    with (ROOT / 'docs/localization/strings.tsv').open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    assert len({row['key'] for row in rows}) == len(rows), 'Duplicate localization key'
    for row in rows:
        assert all(row.get(column) for column in ('key', 'ChineseTraditional', 'English')), row
        fields = lambda value: {name for _, name, _, _ in string.Formatter().parse(value) if name is not None}
        assert fields(row['English']) == fields(row['ChineseTraditional']), 'Placeholder mismatch: ' + row['key']
    return rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    rows = entries()
    # Standalone Core tests and early startup retain a deterministic fallback.
    # Runtime locale snapshots are resolved from RimWorld XML on the main thread.
    defaults = ROOT / 'src/Core/LocalizedText.Defaults.cs'
    generated = '// Generated by tools/Localization.py --write. Edit strings.tsv instead.\n'
    generated += 'using System.Collections.Generic;\nnamespace RimTube.Core\n{\n    public static partial class LocalizedText\n    {\n'
    generated += '        private static readonly Dictionary<string,string> defaults=new Dictionary<string,string>(System.StringComparer.Ordinal)\n        {\n'
    for row in rows:
        generated += '            {' + json.dumps(row['key']) + ',' + json.dumps(row['ChineseTraditional'].replace('\\n', '\n'), ensure_ascii=False) + '},\n'
    generated += '        };\n    }\n}\n'
    # Persisted diagnostics from older sessions can be displayed in the current
    # language without rewriting playlist names, track titles or saved data.
    messages = {}
    for row in rows:
        for language in ('ChineseTraditional', 'English'):
            value = row[language].replace('\\n', '\n')
            messages.setdefault(value, row['key'])
    generated = generated.replace('        };\n    }\n}\n', '        };\n        private static readonly Dictionary<string,string> messageKeys=new Dictionary<string,string>(System.StringComparer.Ordinal)\n        {\n' + ''.join('            {' + json.dumps(value, ensure_ascii=False) + ',' + json.dumps(key) + '},\n' for value, key in messages.items()) + '        };\n    }\n}\n')
    if args.write:
        defaults.write_text(generated, encoding='utf-8')
    else:
        assert defaults.read_text(encoding='utf-8') == generated, 'Outdated Core localization defaults'
    for language in ('English', 'ChineseTraditional'):
        tree = ET.Element('LanguageData')
        for row in rows:
            ET.SubElement(tree, row['key']).text = row[language].replace('\\n', '\n')
        ET.indent(tree, space='  ')
        path = ROOT / 'mod/Common/Languages' / language / 'Keyed/RimTube.xml'
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            ET.ElementTree(tree).write(path, encoding='utf-8', xml_declaration=True)
        else:
            actual = ET.parse(path).getroot()
            assert actual.tag == 'LanguageData', f'Invalid root in {language} XML'
            assert len({el.tag for el in actual}) == len(actual), f'Duplicate key in {language} XML'
            assert {el.tag: el.text for el in actual} == {el.tag: el.text for el in tree}, f'Outdated {language} XML'
        injected = ET.parse(ROOT / 'mod/Common/Languages' / language / 'DefInjected/MainButtonDef/RimTube.xml').getroot()
        assert injected.tag == 'LanguageData', f'Invalid DefInjected root: {language}'
        assert len({el.tag for el in injected}) == len(injected), f'Duplicate DefInjected key: {language}'
        assert {el.tag for el in injected} == {'RimTube.label', 'RimTube.description'}, f'Invalid main button translation keys: {language}'
        assert all(el.text and el.text.strip() for el in injected), f'Empty main button translation: {language}'
    known = {row['key'] for row in rows}
    uses, pending = set(), []
    for path in sorted((ROOT / 'src').rglob('*.cs')):
        if path == defaults:
            continue
        text = path.read_text(encoding='utf-8-sig')
        # Include keys selected by ternary expressions and deferred theme lookup.
        uses.update(re.findall(r'"(RimTube\.[A-Za-z][A-Za-z0-9]*)"', text))
        for match in TOKEN.finditer(text):
            if CJK.search(match.group()):
                pending.append({'file': path.relative_to(ROOT).as_posix(), 'line': text.count('\n', 0, match.start()) + 1, 'literal': match.group()})
    assert uses <= known, 'Undefined translation keys: ' + ', '.join(sorted(uses - known))
    ui = {'ImportUI.cs', 'LibraryPanel.cs', 'MediaUI.cs', 'PlayerUI.cs', 'SettingsPanel.cs', 'TrackDetailsWindow.cs', 'UiHotkeys.cs', 'UiSession.cs'}
    def area(row):
        path = Path(row['file'])
        if path.name in ui:
            return 'interface'
        if path.parent.name == 'Sources':
            return 'sources'
        if path.parent.name == 'Core':
            return 'core'
        return 'game_bridge_and_jobs'
    counts = {name: sum(area(row) == name for row in pending) for name in ('interface', 'sources', 'core', 'game_bridge_and_jobs')}
    report = {'phase': 'Traditional Chinese/English resource migration complete; game layout acceptance tracked separately' if not pending else 'Partial Traditional Chinese/English migration', 'keyCount': len(rows), 'usedKeyCount': len(uses), 'unusedKeys': sorted(known - uses), 'pendingLiteralCount': len(pending), 'pendingByArea': counts, 'pending': pending}
    output = ROOT / 'docs/localization/remaining-literals.json'
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Validated {len(rows)} bilingual keys, {len(uses)} used keys; {len(pending)} C# literals pending migration.')


if __name__ == '__main__':
    main()
